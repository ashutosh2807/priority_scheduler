-- Current operational state. Detailed attempts and operations are in the log.
CREATE TABLE SCHEDULE_EXTG (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SOURCE_ID VARCHAR2(64 CHAR) NOT NULL,
    RECORD_KEY VARCHAR2(160 CHAR) NOT NULL,
    EVENT_SEQ NUMBER NOT NULL,
    JOB_ID NUMBER,
    NAME VARCHAR2(255 CHAR) NOT NULL,
    PACKAGE_NAME VARCHAR2(500 CHAR),
    OCCURRENCE_KEY VARCHAR2(160 CHAR),
    REPORT_DATE DATE,
    PLANNED_EXECUTION_DATE DATE,
    RUN_DATE TIMESTAMP,
    STATUS VARCHAR2(80 CHAR) NOT NULL,
    SAME_DAY NUMBER(1) DEFAULT 0,
    ATTEMPT_NO NUMBER,
    EXECUTED_AT TIMESTAMP,
    RECORDS_LOADED NUMBER,
    ERROR_INFO CLOB,
    CREATED_DATE TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONFIRMATION NUMBER(1) DEFAULT 0,
    RUN_CONFIG CLOB,
    TIME_FLAG NUMBER(1) DEFAULT 0,
    LAST_RUN TIMESTAMP,
    ACTOR VARCHAR2(255 CHAR),
    REASON CLOB,
    WAITING_FOR VARCHAR2(100 CHAR),
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    PAYLOAD CLOB,
    CONSTRAINT UQ_EXTG_LOGGING_RECORD UNIQUE (SOURCE_ID, RECORD_KEY)
);

-- Immutable worker and portal history; replay uses the same event identity.
CREATE TABLE SCHEDULE_EXTG_LOG (
    EVENT_ID VARCHAR2(64 CHAR) PRIMARY KEY,
    SOURCE_ID VARCHAR2(64 CHAR) NOT NULL,
    EVENT_SEQ NUMBER NOT NULL,
    RECORD_KEY VARCHAR2(160 CHAR),
    JOB_ID NUMBER,
    NAME VARCHAR2(255 CHAR),
    REPORT_DATE DATE,
    PLANNED_EXECUTION_DATE DATE,
    STATUS VARCHAR2(80 CHAR),
    EVENT_TYPE VARCHAR2(100 CHAR) NOT NULL,
    OCCURRED_AT TIMESTAMP NOT NULL,
    ACTOR VARCHAR2(255 CHAR),
    REASON CLOB,
    SOURCE VARCHAR2(80 CHAR),
    CORRELATION_ID VARCHAR2(64 CHAR),
    PAYLOAD CLOB,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT UQ_EXTG_LOGGING_SEQUENCE UNIQUE (SOURCE_ID, EVENT_SEQ)
);

CREATE INDEX IX_EXTG_LOGGING_STATUS ON SCHEDULE_EXTG (STATUS, REPORT_DATE);
CREATE INDEX IX_EXTG_LOGGING_JOB ON SCHEDULE_EXTG (JOB_ID, REPORT_DATE);
CREATE INDEX IX_EXTG_LOGGING_EVENTS ON SCHEDULE_EXTG_LOG (JOB_ID, OCCURRED_AT);
CREATE INDEX IX_EXTG_LOGGING_RECORD ON SCHEDULE_EXTG_LOG (SOURCE_ID, RECORD_KEY, EVENT_SEQ);
